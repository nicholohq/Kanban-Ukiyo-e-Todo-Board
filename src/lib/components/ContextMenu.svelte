<script>
	/**
	 * @type {{
	 *   open: boolean,
	 *   x: number,
	 *   y: number,
	 *   task: import('$lib/stores/todoStore.svelte.js').Task|null,
	 *   onaction: (action: string, task: any) => void,
	 *   onclose: () => void
	 * }}
	 */
	let { open, x, y, task, onaction, onclose } = $props();

	let menuEl = $state(null);
	let focusedIndex = $state(0);
	let opener = null;
	let openedAt = 0;

	// React to the menu opening: capture the opener and focus the first item.
	$effect(() => {
		if (open) {
			opener = document.activeElement;
			openedAt = Date.now();
			focusItem(0);
		}
	});

	// Ignore the synthetic click generated by the finger-lift right after a
	// long-press opens the menu; otherwise the overlay would close instantly.
	/** @param {MouseEvent} e */
	function onOverlayClick(e) {
		if (Date.now() - openedAt < 300) return;
		closeWith(onclose);
	}

	/** Restore focus to the element that opened the menu. */
	function restoreFocus() {
		if (opener && typeof opener.focus === 'function') opener.focus();
		opener = null;
	}

	/** @param {() => void} fn */
	function closeWith(cb) {
		restoreFocus();
		cb();
	}

	// Actions derived from the task; "Mark done / Reopen" is dynamic.
	let items = $derived(
		task
			? [
					{ action: 'edit', label: 'Edit' },
					{ action: 'delete', label: 'Delete' },
					{ action: 'duplicate', label: 'Duplicate' },
					{
						action: 'toggle-done',
						label: task.status === 'done' ? 'Reopen' : 'Mark Done'
					},
					{ action: 'cancel', label: 'Cancel' }
				]
			: []
	);

	// Clamp the menu to the viewport, honoring safe-area insets.
	let style = $derived.by(() => {
		if (!open) return '';
		const menuWidth = 180;
		const menuHeight = items.length * 44 + 16;
		const pad = 8;
		const safeLeft = safeArea('left');
		const safeTop = safeArea('top');
		const safeRight = safeArea('right');
		const safeBottom = safeArea('bottom');
		let left = Math.max(safeLeft + pad, Math.min(x, window.innerWidth - safeRight - menuWidth - pad));
		let top = Math.max(safeTop + pad, Math.min(y, window.innerHeight - safeBottom - menuHeight - pad));
		return `left:${left}px;top:${top}px;`;
	});

	function safeArea(side) {
		if (typeof window === 'undefined') return 0;
		const v = getComputedStyle(document.documentElement).getPropertyValue(
			`env(safe-area-inset-${side})`
		);
		const px = parseFloat(v);
		return Number.isFinite(px) ? px : 0;
	}

	function focusItem(index) {
		focusedIndex = (index + items.length) % items.length;
		const item = menuEl?.querySelectorAll('[role="menuitem"]')[focusedIndex];
		item?.focus();
	}

	/** @param {KeyboardEvent} e */
	function onMenuKeydown(e) {
		switch (e.key) {
			case 'ArrowDown':
				e.preventDefault();
				focusItem(focusedIndex + 1);
				break;
			case 'ArrowUp':
				e.preventDefault();
				focusItem(focusedIndex - 1);
				break;
			case 'Home':
				e.preventDefault();
				focusItem(0);
				break;
			case 'End':
				e.preventDefault();
				focusItem(items.length - 1);
				break;
			case 'Escape':
				e.preventDefault();
				closeWith(onclose);
				break;
			case 'Tab':
				// Context menus are not focus traps — Tab closes and moves on.
				closeWith(onclose);
				break;
		}
	}

	/** @param {any} item */
	function handleAction(item) {
		if (item.action === 'cancel') {
			closeWith(onclose);
			return;
		}
		closeWith(() => onaction(item.action, task));
	}
</script>

<svelte:window onkeydown={onMenuKeydown} onscroll={onclose} onresize={onclose} />

{#if open && task}
	<div
		class="ctx-overlay"
		role="presentation"
		onclick={onOverlayClick}
		oncontextmenu={(e) => {
			e.preventDefault();
			closeWith(onclose);
		}}
	>
		<div
			bind:this={menuEl}
			class="ctx-menu"
			style={style}
			role="menu"
			aria-label={`Actions for ${task.title}`}
			onclick={(e) => e.stopPropagation()}
			oncontextmenu={(e) => e.stopPropagation()}
		>
			{#each items as item, i (item.action)}
				<button
					type="button"
					class="ctx-item no-select"
					role="menuitem"
					tabindex={i === focusedIndex ? 0 : -1}
					onclick={() => handleAction(item)}
				>
					{item.label}
				</button>
			{/each}
		</div>
	</div>
{/if}

